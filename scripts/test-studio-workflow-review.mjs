import {reviewAssistantWorkflow} from '../web/studio-workflow-review.mjs';
function testUnified(review){
 let checks=0;
 const eq=(a,b)=>{checks++;if(JSON.stringify(a)!==JSON.stringify(b))throw Error('unified fixture '+checks)};
 const reject=(fn,msg)=>{checks++;let e;try{fn()}catch(x){e=x}if(!e||!String(e.message).includes(msg))throw Error('unified rejection '+checks)};
 const scope={project_id:'p',workflow_id:'w',run_id:'current',plan_sha256:'a'.repeat(64)};
 const plan={goal:'test workflow',steps:[{id:'a',needs:[],effect:'local_compute',success_criteria:'check'},{id:'b',needs:['a'],effect:'local_read',success_criteria:'check'}]};
 const criteria=[{id:'test',required:true,evidence_kind:'automated_check'}];
 const step=(id,status)=>({...scope,id,status});
 const receipt=(s,result)=>({...s,criterion_id:'test',evidence_id:s.run_id+'-e',kind:'automated_check',result});
 const input={scope,plan,criteria,step_observations:[step('a','succeeded'),step('b','succeeded')],evidence:[receipt(scope,'pass')]};
 const on={enabled:true},recall={...on,experienceEnabled:true};
 const x=review(input,on);
 eq(x.priority,'manual_final_review');eq(x.execution_authorized,false);eq(x.completion_verified,false);eq(x.automatic_application,false);
 eq(x.experience.status,'off');eq(x.revision,null);
 eq(review({...input,plan:{...plan,steps:[{...plan.steps[0],effect:'external_write'},plan.steps[1]]}},on).priority,'review_plan_boundaries');
 eq(review({...input,step_observations:[step('b','succeeded')]},on).priority,'reconcile_execution_status');
 eq(review({...input,step_observations:[step('a','succeeded'),step('b','failed')]},on).priority,'review_unfinished_steps');
 eq(review({...input,evidence:[]},on).priority,'review_outcome_evidence');
 eq(review({...input,evidence:[receipt(scope,'fail')]},on).priority,'review_outcome_evidence');
 const prior={...scope,run_id:'prior'};
 const bad={...input,evidence:[receipt(scope,'fail')],prior_run:{scope:prior,observations:[receipt(prior,'pass')]}};
 eq(review(bad,on).priority,'review_lost_criteria');eq(review(bad,on).revision.lost_count,1);
 eq(review({...input,experience:{bad:true}},recall).experience.status,'no_reported_failure');
 eq(review(bad,recall).experience.status,'no_snapshot');
 const run=(name,result)=>{const s={...scope,run_id:name};return {scope:s,observations:[receipt(s,result)]}};
 const attempts=[1,2].map(n=>({correction_code:'fix',before:run('before'+n,'fail'),after:run('after'+n,'pass')}));
 const experience={revision:1,snapshot:{project_id:'p',workflow_id:'w',revision:1,entries:[{correction_code:'fix',criterion_id:'test',status:'active',supporting_pair_count:2}]},attempts};
 const y=review({...bad,experience},recall);
 eq(y.experience.matches.map(m=>m.correction_code),['fix']);eq(y.priority,'review_lost_criteria');eq(y.execution_authorized,false);
 eq(review({...bad,experience},on).experience.matches,[]);
 eq(review({...input,evidence:[],experience},recall).experience.status,'no_reported_failure');
 eq(review(null).status,'off');eq(review(null,{...recall,isolated:true}).status,'isolated');
 reject(()=>review({...input,step_observations:[{...step('a','succeeded'),run_id:'other'}]},on),'step-scope-mismatch');
 reject(()=>review({...input,step_observations:[{...step('a','succeeded'),workflow_id:'other'}]},on),'step-scope-mismatch');
 reject(()=>review({...input,scope:{...scope,plan_sha256:'bad'}},on),'invalid-review-scope');
 reject(()=>review({...bad,experience:{...experience,revision:0}},recall),'recall-scope-mismatch');
 reject(()=>review({...input,prior_run:{scope,observations:input.evidence}},on),'comparison-scope-mismatch');
 reject(()=>review({...input,evidence:[{...input.evidence[0],workflow_id:'other'}]},on),'observation-scope-mismatch');
 const {workflow_id:ignored,...unscopedReceipt}=input.evidence[0];
 reject(()=>review({...input,evidence:[unscopedReceipt]},on),'observation-scope-mismatch');
 const foreignExperience={...experience,attempts:attempts.map((a,i)=>i===0?{...a,before:{...a.before,observations:[{...a.before.observations[0],workflow_id:'other'}]}}:a)};
 reject(()=>review({...bad,experience:foreignExperience},recall),'observation-scope-mismatch');
 const withFirst=(first)=>({...experience,attempts:[first,attempts[1]]});
 const currentBefore=withFirst({...attempts[0],before:run(scope.run_id,'fail')});
 const currentAfter=withFirst({...attempts[0],after:run(scope.run_id,'pass')});
 reject(()=>review({...bad,experience:currentBefore},recall),'current-run-in-experience');
 reject(()=>review({...bad,experience:currentAfter},recall),'current-run-in-experience');
 const reuseReceipt=(r)=>({...r,observations:[{...r.observations[0],evidence_id:bad.evidence[0].evidence_id}]});
 const reuseBefore=withFirst({...attempts[0],before:reuseReceipt(attempts[0].before)});
 const reuseAfter=withFirst({...attempts[0],after:reuseReceipt(attempts[0].after)});
 reject(()=>review({...bad,experience:reuseBefore},recall),'current-evidence-in-experience');
 reject(()=>review({...bad,experience:reuseAfter},recall),'current-evidence-in-experience');
 eq(review({...bad,experience:currentBefore},on).experience.status,'off');
 eq(review({...bad,experience:{...experience,attempts:[]}},recall).experience.status,'no_current_evidence');
 reject(()=>review(input,{enabled:true,experienceEnabled:1}),'invalid-options');
 eq(JSON.stringify(x).includes('current-e'),false);
 eq(input.step_observations.length,2);
 return checks;
}
console.log('UNIFIED WORKFLOW REVIEW: PASS ('+testUnified(reviewAssistantWorkflow)+' checks)');
