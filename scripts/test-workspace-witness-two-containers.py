#!/usr/bin/env python3
"""CI-only two-container SSH custodian acceptance with separate Docker volumes.

Host orchestration can control both containers and is NOT an independent
third-party custodian; this tests actual TCP/container isolation, private key
separation, pinned SSH host identity and recovery from loss of receiver DATA.
No host ports, production account, real user files or API trust changes.
"""
import hashlib
import json
import os
from pathlib import Path
import secrets
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parent.parent
IMAGEFILE = ROOT / "deploy" / "witness-ci" / "Dockerfile"
SERVER_HOME = "/home/witness"
BIN = "/opt/nexus-witness"
STORE = SERVER_HOME + "/stateholder/receiver"
ACK_KEY = SERVER_HOME + "/keys/receiver.pem"
CONF = "/etc/nexus-witness/receiver.json"
SSH_USER = "witness"


def call(*argv, ok=True, timeout=90):
    p = subprocess.run([str(x) for x in argv], capture_output=True,
                       text=True, timeout=timeout, check=False)
    if (p.returncode == 0) != ok:
        raise AssertionError(
            "Unexpected command status=" + str(p.returncode)
            + " expected_success=" + str(ok)
            + " command=" + repr(argv)
            + " stdout=" + repr(p.stdout[-1400:])
            + " stderr=" + repr(p.stderr[-1600:])
        )
    return p.stdout


def docker(*args, ok=True, timeout=90):
    return call("docker", *args, ok=ok, timeout=timeout)


def inside(container, *args, user=None, ok=True):
    cmd = ["exec"]
    if user:
        cmd += ["--user", user]
    cmd += [container, *args]
    return docker(*cmd, ok=ok)


def python(container, filename, *args, user=None, ok=True):
    return inside(container, "python3", "-I", BIN + "/" + filename,
                  *args, user=user, ok=ok)


def transfer_public(source, source_file, target, destination, staging):
    scratch = staging / ("public-" + secrets.token_hex(8))
    docker("cp", source + ":" + source_file, scratch)
    docker("cp", scratch, target + ":" + destination)
    scratch.unlink()


def copy_signed(source, source_file, target, target_file, staging):
    transfer_public(source, source_file, target, target_file, staging)


def configure_server(server, *, initialize, renew_host, staging, client):
    inside(server, "sh", "-ec",
           "mkdir -p /home/witness/stateholder /home/witness/keys /etc/ssh/keys "
           "/etc/nexus-witness /run/sshd; "
           "chown witness:witness /home/witness/stateholder /home/witness/keys; "
           "chmod 0700 /home/witness/stateholder /home/witness/keys /etc/ssh/keys")
    if renew_host:
        inside(server, "ssh-keygen", "-q", "-t", "ed25519", "-N", "",
               "-f", "/etc/ssh/keys/ssh_host_ed25519")
    if initialize:
        inside(server, "openssl", "genpkey", "-algorithm", "Ed25519",
               "-out", ACK_KEY, user=SSH_USER)
        inside(server, "chmod", "0600", ACK_KEY)
        inside(server, "openssl", "pkey", "-in", ACK_KEY,
               "-pubout", "-out", "/tmp/ack.pub")
    else:
        inside(server, "openssl", "pkey", "-in", ACK_KEY,
               "-pubout", "-out", "/tmp/ack.pub")
    transfer_public(client, "/work/witness.pub", server,
                    "/tmp/source.pub", staging)
    transfer_public(client, "/work/client-ssh.pub", server,
                    "/tmp/client-ssh.pub", staging)
    transfer_public(server, "/tmp/ack.pub", client,
                    "/work/ack.pub", staging)
    if initialize:
        python(server, "workspace-witness-custodian.py", "init",
               "--store", STORE, "--receiver-id", "receiver-separate-container",
               "--source-key-id", "source-witness",
               "--source-public-key", "/tmp/source.pub",
               "--ack-key-id", "receiver-ack",
               "--ack-public-key", "/tmp/ack.pub", user=SSH_USER)

    # Synthetic fixture only: root-owned config and authorized_keys are
    # generated by the Docker test controller. Client input cannot edit paths.
    config = {
        "schema": "nexus.offsite.root-pinned-launch.v1",
        "store_dir": STORE,
        "ack_private_key": ACK_KEY,
    }
    inside(server, "python3", "-c",
           "import json,os; p=" + repr(CONF) + "; "
           "open(p,'w').write(json.dumps(" + repr(config) + "));"
           "os.chmod(p,0o644)")
    sshline = (
        'restrict,command="/usr/bin/python3 -I ' + BIN
        + '/workspace-witness-host.py serve --config ' + CONF
        + '" '
    )
    inside(server, "python3", "-c",
           "import os; p='/etc/ssh/witness_authorized_keys'; "
           "k=open('/tmp/client-ssh.pub').read().strip(); "
           "open(p,'w').write(" + repr(sshline) + "+k+'\\n');"
           "os.chmod(p,0o644)")
    sshd = (
        "Port 22\n"
        "ListenAddress 0.0.0.0\n"
        "HostKey /etc/ssh/keys/ssh_host_ed25519\n"
        "PidFile /run/sshd/sshd.pid\n"
        "AuthorizedKeysFile /etc/ssh/witness_authorized_keys\n"
        "PasswordAuthentication no\n"
        "KbdInteractiveAuthentication no\n"
        "UsePAM yes\n"
        "PubkeyAuthentication yes\n"
        "AuthenticationMethods publickey\n"
        "PermitRootLogin no\n"
        "AllowAgentForwarding no\n"
        "AllowTcpForwarding no\n"
        "X11Forwarding no\n"
        "PermitTunnel no\n"
        "PermitTTY no\n"
        "PermitUserEnvironment no\n"
        "PermitUserRC no\n"
        "StrictModes yes\n"
        "LogLevel ERROR\n"
    )
    inside(server, "python3", "-c",
           "open('/etc/ssh/sshd_nexus.conf','w').write(" + repr(sshd) + ")")
    python(server, "workspace-witness-host.py", "check",
           "--config", CONF, user=SSH_USER)
    inside(server, "/usr/sbin/sshd", "-t",
           "-f", "/etc/ssh/sshd_nexus.conf")
    docker("exec", "-d", server, "/usr/sbin/sshd", "-D",
           "-f", "/etc/ssh/sshd_nexus.conf", "-e")


def client_setup(client):
    inside(client, "sh", "-ec", "mkdir -p /work; chmod 0700 /work")
    for kind in ("data", "witness"):
        inside(client, "openssl", "genpkey", "-algorithm", "Ed25519",
               "-out", "/work/" + kind + ".pem")
        inside(client, "chmod", "0600", "/work/" + kind + ".pem")
        inside(client, "openssl", "pkey", "-in", "/work/" + kind + ".pem",
               "-pubout", "-out", "/work/" + kind + ".pub")
    inside(client, "ssh-keygen", "-q", "-t", "ed25519",
           "-N", "", "-f", "/work/client-ssh")
    python(client, "workspace-trust.py", "init",
           "--state-dir", "/work/trust")
    python(client, "workspace-trust.py", "enroll",
           "--state-dir", "/work/trust", "--key-id", "data-source",
           "--public-key", "/work/data.pub")


def install_pinned_host_public(server, client, staging, *, valid=True):
    # A distinct ceremony MUST approve the host key in real deployment.
    # Here the disposable test controller copies the pubkey directly.
    if valid:
        transfer_public(server, "/etc/ssh/keys/ssh_host_ed25519.pub",
                        client, "/work/server-host.pub", staging)
        pub = "/work/server-host.pub"
    else:
        inside(client, "ssh-keygen", "-q", "-t", "ed25519", "-N", "",
               "-f", "/work/wrong-host")
        pub = "/work/wrong-host.pub"
    inside(client, "python3", "-c",
           "p=open(" + repr(pub) + ").read().split(); "
           "open('/work/known_hosts','w').write('receiver '+p[0]+' '+p[1]+'\\n');"
           "import os; os.chmod('/work/known_hosts',0o600)")


def await_server(client):
    snippet = (
        "import socket,sys; s=socket.socket(); s.settimeout(1); "
        "s.connect(('receiver',22)); s.close()"
    )
    for _ in range(50):
        p = subprocess.run(
            ["docker", "exec", client, "python3", "-c", snippet],
            capture_output=True, timeout=6,
        )
        if p.returncode == 0:
            return
        time.sleep(0.2)
    raise AssertionError("receiver SSH did not accept TCP on isolated Docker network")


def seal(client, label):
    path = "/work/" + label + ".json"
    python(client, "workspace-offsite-witness.py", "seal",
           "--state-dir", "/work/trust",
           "--witness-key-id", "source-witness",
           "--witness-private-key", "/work/witness.pem",
           "--output", path)
    return path


def send_args(action, path, sequence):
    base = [
        "--host", "receiver", "--user", SSH_USER,
        "--known-hosts", "/work/known_hosts",
        "--identity", "/work/client-ssh",
        "--receiver-id", "receiver-separate-container",
        "--source-key-id", "source-witness",
        "--source-public-key", "/work/witness.pub",
        "--ack-key-id", "receiver-ack",
        "--ack-public-key", "/work/ack.pub",
        "--minimum-sequence", str(sequence),
        "--state-dir", "/work/trust",
        "--output", path,
    ]
    return [action, *base]


def server_container(server, image, network, data_volume, keys_volume, hosts_volume):
    return docker("run", "-d", "--name", server,
                  "--network", network, "--network-alias", "receiver",
                  "--mount", f"type=volume,source={data_volume},target=/home/witness/stateholder",
                  "--mount", f"type=volume,source={keys_volume},target=/home/witness/keys",
                  "--mount", f"type=volume,source={hosts_volume},target=/etc/ssh/keys",
                  image, "sleep", "infinity").strip()


def client_container(client, image, network, work_volume):
    return docker("run", "-d", "--name", client,
                  "--network", network,
                  "--mount", f"type=volume,source={work_volume},target=/work",
                  image, "sleep", "infinity").strip()


def signed_package(client, path):
    return json.loads(inside(client, "cat", path))


def main():
    token = secrets.token_hex(6)
    image = "nexus-witness-two-domain-test:" + token
    network = "nexus-witness-test-net-" + token
    server = "nexus-witness-test-srv-" + token
    client = "nexus-witness-test-client-" + token
    data_vol = "nexus-witness-data-" + token
    key_vol = "nexus-witness-signer-" + token
    host_vol = "nexus-witness-hostkeys-" + token
    client_vol = "nexus-witness-client-" + token
    swapped_host_vol = "nexus-witness-hostkeys-swap-" + token
    volumes = [data_vol, key_vol, host_vol, client_vol, swapped_host_vol]
    if os.name != "posix":
        raise AssertionError("POSIX Docker daemon required")
    with tempfile.TemporaryDirectory(prefix="nexus-witness-docker-") as td:
        staging = Path(td)
        try:
            docker("build", "-f", IMAGEFILE, "-t", image, ROOT, timeout=240)
            docker("network", "create", "--internal", network)
            for volume in volumes:
                docker("volume", "create", volume)
            client_container(client, image, network, client_vol)
            client_setup(client)
            server_container(server, image, network, data_vol, key_vol, host_vol)
            # No common bind mount: the source signer private key exists
            # only in the client volume; recipient key only in receiver volume.
            inside(client, "sh", "-c",
                   "test ! -e /home/witness/keys/receiver.pem")
            inside(server, "sh", "-c", "test ! -e /work/witness.pem")
            configure_server(server, initialize=True, renew_host=True,
                             staging=staging, client=client)
            install_pinned_host_public(server, client, staging)
            await_server(client)

            first = seal(client, "state-one")
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("send", "/work/ack-one.json", 1),
                   "--receipt", first)
            first_ack = signed_package(client, "/work/ack-one.json")
            assert first_ack["ack"]["sequence"] == 1
            latest = signed_package(client, "/work/ack-one.json")

            # Independent SSH key pinning: an authenticated receiver with
            # a different presented host key must not be accepted.
            install_pinned_host_public(server, client, staging, valid=False)
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("latest", "/work/wrong-host-ack.json", 1),
                   ok=False)
            inside(client, "sh", "-c",
                   "test ! -e /work/wrong-host-ack.json")
            install_pinned_host_public(server, client, staging)
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("latest", "/work/pre-restart.json", 1))
            assert signed_package(client, "/work/pre-restart.json") == latest

            # Controlled cross-volume backup: only signed *public* receiver
            # history, source/ack public keys and an independently retained
            # last signed acknowledgment are transported.
            copy_signed(client, "/work/ack-one.json", server,
                        "/tmp/last-approved.json", staging)
            python(server, "workspace-witness-recovery.py", "export",
                   "--store", STORE, "--backup", "/tmp/backup.json",
                   "--trusted-checkpoint", "/tmp/last-approved.json",
                   "--expected-receiver-id", "receiver-separate-container",
                   "--trusted-source-key-id", "source-witness",
                   "--trusted-source-public-key", "/tmp/source.pub",
                   "--trusted-ack-key-id", "receiver-ack",
                   "--trusted-ack-public-key", "/tmp/ack.pub",
                   "--minimum-sequence", "1", user=SSH_USER)
            copy_signed(server, "/tmp/backup.json", client,
                        "/work/receiver-backup.json", staging)

            # Destroy the entire receiver DATA volume, not source client,
            # recipient signer-key volume or known-good SSH host-key volume.
            docker("rm", "-f", server)
            docker("volume", "rm", data_vol)
            docker("volume", "create", data_vol)
            server_container(server, image, network, data_vol, key_vol, host_vol)
            # Do not accept a new history or quietly create a fresh signer.
            # Only a verified backup + independently retained latest package
            # can rebuild the receiver before sshd is started.
            inside(server, "sh", "-ec",
                   "mkdir -p /home/witness/stateholder; "
                   "chown witness:witness /home/witness/stateholder; "
                   "chmod 0700 /home/witness/stateholder")
            copy_signed(client, "/work/receiver-backup.json", server,
                        "/tmp/backup.json", staging)
            copy_signed(client, "/work/ack-one.json", server,
                        "/tmp/last-approved.json", staging)
            transfer_public(client, "/work/witness.pub", server,
                            "/tmp/source.pub", staging)
            inside(server, "openssl", "pkey", "-in", ACK_KEY,
                   "-pubout", "-out", "/tmp/ack.pub")
            python(server, "workspace-witness-recovery.py", "restore",
                   "--new-store", STORE, "--backup", "/tmp/backup.json",
                   "--trusted-checkpoint", "/tmp/last-approved.json",
                   "--expected-receiver-id", "receiver-separate-container",
                   "--trusted-source-key-id", "source-witness",
                   "--trusted-source-public-key", "/tmp/source.pub",
                   "--trusted-ack-key-id", "receiver-ack",
                   "--trusted-ack-public-key", "/tmp/ack.pub",
                   "--minimum-sequence", "1", user=SSH_USER)
            configure_server(server, initialize=False, renew_host=False,
                             staging=staging, client=client)
            await_server(client)
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("latest", "/work/after-loss.json", 1))
            assert signed_package(client, "/work/after-loss.json") == latest

            # A container with old receiver state and another SSH host
            # identity is not trusted merely because it has the right signed
            # source receipt and acknowledged state.
            docker("rm", "-f", server)
            server_container(server, image, network, data_vol, key_vol,
                             swapped_host_vol)
            configure_server(server, initialize=False, renew_host=True,
                             staging=staging, client=client)
            await_server(client)
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("latest", "/work/host-swap.json", 1),
                   ok=False)
            inside(client, "sh", "-c", "test ! -e /work/host-swap.json")
            docker("rm", "-f", server)
            server_container(server, image, network, data_vol, key_vol,
                             host_vol)
            configure_server(server, initialize=False, renew_host=False,
                             staging=staging, client=client)
            await_server(client)
            python(client, "workspace-witness-ssh-client.py",
                   *send_args("latest", "/work/final.json", 1))
            assert signed_package(client, "/work/final.json") == latest
            print("NEXUS TWO-CONTAINER WITNESS: PASS "
                  "(real private Docker TCP SSH, isolated volumes, data loss, signed recovery, spoofed host denied)")
        finally:
            # Cleanup is best effort even when initialization or the SSH
            # handshake failed; never hide the primary regression traceback.
            for name in (server, client):
                subprocess.run(["docker", "rm", "-f", name], capture_output=True,
                               timeout=15, check=False)
            subprocess.run(["docker", "network", "rm", network],
                           capture_output=True, timeout=15, check=False)
            for volume in volumes:
                subprocess.run(["docker", "volume", "rm", volume],
                               capture_output=True, timeout=15, check=False)
            subprocess.run(["docker", "image", "rm", "-f", image],
                           capture_output=True, timeout=15, check=False)


if __name__ == "__main__":
    main()
