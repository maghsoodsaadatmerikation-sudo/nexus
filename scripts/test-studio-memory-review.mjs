import assert from 'node:assert/strict';
import {reviewMemory,reviewMemoryConflicts} from '../web/studio-memory-review.mjs';
const notes=Object.freeze(['Piano music','Piano music','Piano music composition','Other note']);
assert.deepEqual(reviewMemory(notes,'piano'),{status:'off',matches:[],duplicates:[]});
assert.deepEqual(reviewMemory(null,null,{enabled:true,isolated:true}),{status:'isolated',matches:[],duplicates:[]});
const ranked=reviewMemory(notes,'piano composition',{enabled:true});
assert.deepEqual(ranked.matches,[{index:2,score:2},{index:0,score:1}]);
assert.deepEqual(ranked.duplicates,[{index:1,first_index:0}]);
assert.equal(JSON.stringify(ranked).includes('Piano music'),false);
assert.equal(reviewMemory(notes,'piano',{enabled:true,limit:1}).truncated,true);
assert.deepEqual(reviewMemory(['کتاب موسیقی','گیتار'],'كتاب',{enabled:true}).matches,[{index:0,score:1}]);
assert.deepEqual(reviewMemory(['Café','Cafe\u0301'],'café',{enabled:true}).duplicates,[{index:1,first_index:0}]);
assert.deepEqual(reviewMemory(['NOT approved','approved'],'approved',{enabled:true}).duplicates,[]);
assert.deepEqual(reviewMemory(notes,'unknown',{enabled:true}).matches,[]);
assert.throws(()=>reviewMemory(Array(31).fill('note'),'x',{enabled:true}));
assert.throws(()=>reviewMemory(['x'.repeat(501)],'x',{enabled:true}));
assert.throws(()=>reviewMemory(notes,'x',{enabled:true,limit:0}));
assert.throws(()=>reviewMemory(notes,'x',{enabled:1}));
assert.deepEqual(notes,['Piano music','Piano music','Piano music composition','Other note']);
const conflicts=Object.freeze(['[fact] city = A','[fact] city = B','[fact] city = A','city = C','[fact] other = X']);
assert.deepEqual(reviewMemoryConflicts(conflicts,{enabled:true}).groups,[{alternatives:[[0,2],[1]]}]);
assert.deepEqual(reviewMemoryConflicts(conflicts).groups,[]);
assert.deepEqual(reviewMemoryConflicts(null,{enabled:true,isolated:true}),{status:'isolated',groups:[]});
assert.deepEqual(reviewMemoryConflicts(['[fact] شهر = الف','[fact] شهر = ب'],{enabled:true}).groups,[{alternatives:[[0],[1]]}]);
assert.deepEqual(reviewMemoryConflicts(['[fact] x = Café','[fact] x = Cafe\u0301'],{enabled:true}).groups,[]);
assert.deepEqual(reviewMemoryConflicts(['[fact] x = yes','[fact] X = no','[fact] x =  '],{enabled:true}).groups,[]);
assert.deepEqual(reviewMemoryConflicts(['city: A','city: B','[fact] city = A\nB'],{enabled:true}).groups,[]);
assert.throws(()=>reviewMemoryConflicts(['x'.repeat(501)],{enabled:true}));
assert.throws(()=>reviewMemoryConflicts(Array(31).fill('x'),{enabled:true}));
assert.throws(()=>reviewMemoryConflicts(conflicts,{isolated:'yes'}));
assert.equal(JSON.stringify(reviewMemoryConflicts(conflicts,{enabled:true})).includes('city'),false);
assert.equal(conflicts.length,5);
console.log('MEMORY REVIEW CORE: PASS');
