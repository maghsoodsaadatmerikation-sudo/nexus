import assert from 'node:assert/strict';
import {proposeMemoryEdit,applyMemoryEdit} from '../web/studio-memory-edits.mjs';
const notes=Object.freeze(['first','second']);
const review=proposeMemoryEdit('project-a',notes,{kind:'replace',index:1,value:'updated'});
assert.deepEqual(applyMemoryEdit('project-a',notes,review,{approved:true}),['first','updated']);
assert.deepEqual(notes,['first','second']);
assert.throws(()=>applyMemoryEdit('project-a',notes,review),/not-approved/);
assert.throws(()=>applyMemoryEdit('project-a',notes,review,{approved:1}),/not-approved/);
assert.throws(()=>applyMemoryEdit('project-b',notes,review,{approved:true}),/project-mismatch/);
assert.throws(()=>applyMemoryEdit('project-a',['changed','second'],review,{approved:true}),/stale/);
assert.throws(()=>applyMemoryEdit('project-a',['second','first'],review,{approved:true}),/stale/);
assert.throws(()=>applyMemoryEdit('project-a',notes,review,{approved:true,isolated:true}),/not-approved/);
assert.throws(()=>proposeMemoryEdit('project-a',null,null,{isolated:true}),/isolated/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'remove',index:2}),/index/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'add',value:' '}),/invalid/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'add',value:'x'.repeat(501)}),/invalid/);
assert.throws(()=>proposeMemoryEdit('project-a',Array(30).fill('x'),{kind:'add',value:'y'}),/capacity/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'remove',index:0,hidden:true}),/invalid/);
const add=proposeMemoryEdit('project-a',notes,{kind:'add',value:'third'});
assert.deepEqual(applyMemoryEdit('project-a',notes,add,{approved:true}),['first','second','third']);
const remove=proposeMemoryEdit('project-a',notes,{kind:'remove',index:0});
assert.deepEqual(applyMemoryEdit('project-a',notes,remove,{approved:true}),['second']);
assert.equal(Object.isFrozen(review.expected)&&Object.isFrozen(review.operation),true);
console.log('MEMORY EDIT REVIEW: PASS');
