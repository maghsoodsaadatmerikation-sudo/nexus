import assert from 'node:assert/strict';
import {proposeMemoryEdit,applyMemoryEdit} from '../web/studio-memory-edits.mjs';
const notes=Object.freeze(['first','second']);
const review=proposeMemoryEdit('project-a',notes,{kind:'replace',index:1,value:'updated'});
assert.deepEqual(applyMemoryEdit('project-a',notes,review,{approved:true}),['first','updated']);
assert.deepEqual(notes,['first','second']);
assert.throws(()=>applyMemoryEdit('project-a',notes,review),/not-approved/);
assert.throws(()=>applyMemoryEdit('project-a',notes,review,{approved:1}),/not-approved/);
assert.throws(()=>applyMemoryEdit('project-b',notes,review,{approved:true}),/project-mismatch/);
assert.throws(()=>applyMemoryEdit('project-a',['changed','second'],review,{approved:true}),/stale/);
assert.throws(()=>applyMemoryEdit('project-a',['second','first'],review,{approved:true}),/stale/);
assert.throws(()=>applyMemoryEdit('project-a',notes,review,{approved:true,isolated:true}),/not-approved/);
assert.throws(()=>proposeMemoryEdit('project-a',null,null,{isolated:true}),/isolated/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'remove',index:2}),/index/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'add',value:' '}),/invalid/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'add',value:'x'.repeat(501)}),/invalid/);
assert.throws(()=>proposeMemoryEdit('project-a',Array(30).fill('x'),{kind:'add',value:'y'}),/capacity/);
assert.throws(()=>proposeMemoryEdit('project-a',notes,{kind:'remove',index:0,hidden:true}),/invalid/);
const add=proposeMemoryEdit('project-a',notes,{kind:'add',value:'third'});
assert.deepEqual(applyMemoryEdit('project-a',notes,add,{approved:true}),['first','second','third']);
const remove=proposeMemoryEdit('project-a',notes,{kind:'remove',index:0});
assert.deepEqual(applyMemoryEdit('project-a',notes,remove,{approved:true}),['second']);
assert.equal(Object.isFrozen(review.expected)&&Object.isFrozen(review.operation),true);
console.log('MEMORY EDIT REVIEW: PASS');

const {createMemoryEditReview}=await import('../web/studio-memory-edits.mjs');
const controller=createMemoryEditReview();
const opts={revision:1,approved:true};
const stage=()=>controller.stage('project-a',notes,{kind:'add',value:'third'},{revision:1});
let staged=stage();
assert.deepEqual(Object.keys(staged).sort(),['operation','project_id','ticket']);
assert.equal(Object.isFrozen(staged)&&Object.isFrozen(staged.ticket),true);
assert.deepEqual(controller.approve(staged.ticket,'project-a',notes,opts),['first','second','third']);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.approve({},'project-a',notes,opts),/inactive/);
assert.deepEqual(controller.approve(staged.ticket,'project-a',notes,opts),['first','second','third']);
staged=stage();
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,{...opts,revision:2}),/stale-memory-revision/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.approve(staged.ticket,'project-b',notes,opts),/project-mismatch/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,{...opts,approved:false}),/not-approved/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,{...opts,isolated:true}),/not-approved/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.approve(staged.ticket,'project-a',['changed'],opts),/stale/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
const replacement=stage();
assert.equal(controller.cancel(staged.ticket),false);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
assert.equal(controller.cancel(replacement.ticket),true);
assert.throws(()=>controller.approve(replacement.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
controller.invalidate();
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
assert.throws(()=>controller.stage('project-a',notes,{kind:'remove',index:0},{revision:-1}),/invalid-memory-revision/);
assert.throws(()=>controller.approve(staged.ticket,'project-a',notes,opts),/inactive/);
staged=stage();
const other=createMemoryEditReview();
assert.throws(()=>other.approve(staged.ticket,'project-a',notes,opts),/inactive/);
assert.deepEqual(notes,['first','second']);
console.log('ONE-USE MEMORY REVIEW: PASS');
