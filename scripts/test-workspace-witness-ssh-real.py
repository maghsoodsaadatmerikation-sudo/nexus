#!/usr/bin/env python3
"""Real local OpenSSH daemon + pinned client + NEXUS Ed25519 custodian pilot.

Runs only against loopback on a disposable high port. No external host, live
user data, production secret, or separate operational trust domain is touched.
Unlike the fake-ssh contract fixture this executes a real sshd and SSH handshake.
"""

import getpass
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import sys
import tempfile
import time

HERE = Path(__file__).resolve().parent
TRUST = HERE / "workspace-trust.py"
WITNESS = HERE / "workspace-offsite-witness.py"
CUSTODIAN = HERE / "workspace-witness-custodian.py"
CLIENT = HERE / "workspace-witness-ssh-client.py"
RECEIVER = HERE / "workspace-witness-ssh-receiver.py"


def execute(binary, *args, success=True, timeout=45):
    command = [str(binary), *map(str, args)]
    result = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    if (result.returncode == 0) != success:
        raise AssertionError(
            f"expected success={success}, exit={result.returncode} "
            f"command={command!r}\nstdout={result.stdout!r}\nstderr={result.stderr!r}"
        )
    return result


def tool(path, *args, success=True):
    return execute(sys.executable, path, *args, success=success)


def ed25519(root, name):
    secret = root / (name + ".pem")
    public = root / (name + ".pub.pem")
    execute("openssl", "genpkey", "-algorithm", "Ed25519", "-out", secret)
    os.chmod(secret, 0o600)
    execute("openssl", "pkey", "-in", secret, "-pubout", "-out", public)
    return secret, public


def ssh_key(root, name):
    secret = root / name
    execute("ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", secret)
    assert secret.stat().st_mode & 0o077 == 0
    return secret, secret.with_name(secret.name + ".pub")


def free_loopback_port():
    with socket.socket() as connection:
        connection.bind(("127.0.0.1", 0))
        return connection.getsockname()[1]


def write_forced_command(root, store, secret, drop_marker):
    wrapper = root / "forced-receiver.py"
    # All paths are generated by this test beneath a fresh private directory.
    script = (
        "#!/usr/bin/env python3\n"
        "import os, subprocess, sys\n"
        "from pathlib import Path\n"
        f"os.environ['NEXUS_CUSTODIAN_STORE'] = {str(store)!r}\n"
        f"os.environ['NEXUS_CUSTODIAN_ACK_KEY'] = {str(secret)!r}\n"
        "raw = sys.stdin.buffer.read(8193)\n"
        "if len(raw) > 8192:\n"
        "    sys.exit(87)\n"
        f"process = subprocess.run([sys.executable, {str(RECEIVER)!r}],"
        " input=raw, capture_output=True, timeout=30, env=os.environ)\n"
        f"marker = Path({str(drop_marker)!r})\n"
        "if (process.returncode == 0 and marker.exists()\n"
        "        and os.environ.get('SSH_ORIGINAL_COMMAND') == 'nexus-witness-v1 receive'):\n"
        "    marker.unlink()\n"
        "    sys.exit(92)  # reply lost AFTER durable write\n"
        "sys.stdout.buffer.write(process.stdout)\n"
        "sys.stderr.buffer.write(process.stderr)\n"
        "sys.exit(process.returncode)\n"
    )
    wrapper.write_text(script)
    os.chmod(wrapper, 0o700)
    return wrapper


def make_sshd_config(root, port, host_key, authorized_keys):
    config = root / "sshd.conf"
    config.write_text(
        f"Port {port}\n"
        "ListenAddress 127.0.0.1\n"
        f"HostKey {host_key}\n"
        f"PidFile {root / 'sshd.pid'}\n"
        f"AuthorizedKeysFile {authorized_keys}\n"
        "PasswordAuthentication no\n"
        "KbdInteractiveAuthentication no\n"
        "UsePAM no\n"
        "PubkeyAuthentication yes\n"
        "AuthenticationMethods publickey\n"
        "PermitRootLogin no\n"
        "AllowAgentForwarding no\n"
        "AllowTcpForwarding no\n"
        "X11Forwarding no\n"
        "PermitTunnel no\n"
        "PermitTTY no\n"
        "PermitUserEnvironment no\n"
        "PermitUserRC no\n"
        "StrictModes yes\n"
        "LogLevel ERROR\n"
    )
    return config


def start_sshd(config, log):
    binary = shutil.which("sshd") or "/usr/sbin/sshd"
    if not Path(binary).is_file():
        raise AssertionError("OpenSSH server missing: install openssh-server in CI")
    # On Ubuntu hosted CI runners, sshd uses a root-owned privilege-separation
    # monitor, while test data and authorized_keys stay runner-owned.
    execute("sudo", "-n", binary, "-t", "-f", config)
    stream = log.open("ab", buffering=0)
    process = subprocess.Popen(
        ["sudo", "-n", binary, "-D", "-e", "-f", str(config)],
        stdout=subprocess.DEVNULL, stderr=stream,
    )
    port = next(int(line.split()[1]) for line in config.read_text().splitlines()
                if line.startswith("Port "))
    for _ in range(100):
        if process.poll() is not None:
            break
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=0.1):
                return process, stream
        except OSError:
            time.sleep(0.1)
    stream.close()
    raise AssertionError("ephemeral sshd failed to listen; see CI runner SSH logs")


def stop_sshd(process, stream, root):
    pidfile = root / "sshd.pid"
    if pidfile.is_file():
        pid = pidfile.read_text().strip()
        if pid.isdecimal():
            subprocess.run(["sudo", "-n", "kill", "-TERM", pid],
                           capture_output=True, check=False, timeout=8)
    process.terminate()
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait(timeout=5)
    stream.close()


def main():
    if os.name != "posix" or shutil.which("sudo") is None:
        raise AssertionError("real OpenSSH test requires POSIX runner with sudo")
    if shutil.which("ssh") is None or shutil.which("ssh-keygen") is None:
        raise AssertionError("real OpenSSH client and ssh-keygen required")
    # The home directory is important: sshd's StrictModes rejects overly
    # permissive temporary ancestors. Never touch the operator's ~/.ssh.
    with tempfile.TemporaryDirectory(
        prefix=".nexus-sshd-regression-", dir=Path.home()
    ) as directory:
        root = Path(directory)
        os.chmod(root, 0o700)
        source = root / "source-registry"
        custodian = root / "custodian-ledger"
        receipts = root / "receipts"
        receipts.mkdir(mode=0o700)
        data_secret, data_pub = ed25519(root, "data")
        data_secret_2, data_pub_2 = ed25519(root, "data-2")
        source_secret, source_pub = ed25519(root, "offsite-receipt")
        ack_secret, ack_pub = ed25519(root, "ack")
        ssh_secret, ssh_pub = ssh_key(root, "ssh-client")
        wrong_secret, wrong_pub = ssh_key(root, "unapproved-client")
        host_secret, host_pub = ssh_key(root, "sshd-host")
        other_host_secret, other_host_pub = ssh_key(root, "untrusted-host")

        tool(TRUST, "init", "--state-dir", source)
        tool(TRUST, "enroll", "--state-dir", source,
             "--key-id", "data-a", "--public-key", data_pub)
        tool(CUSTODIAN, "init", "--store", custodian,
             "--receiver-id", "independent-ssh-loopback",
             "--source-key-id", "external-witness",
             "--source-public-key", source_pub,
             "--ack-key-id", "independent-ack",
             "--ack-public-key", ack_pub)

        marker = root / "drop-one-reply"
        forced = write_forced_command(root, custodian, ack_secret, marker)
        authorized = root / "authorized_keys"
        authorized.write_text(
            f'restrict,command="{forced}" {ssh_pub.read_text().strip()}\n'
        )
        os.chmod(authorized, 0o600)

        port = free_loopback_port()
        known_hosts = root / "known_hosts"
        parts = host_pub.read_text().split()
        known_hosts.write_text(
            f"[127.0.0.1]:{port} {parts[0]} {parts[1]}\n"
        )
        os.chmod(known_hosts, 0o600)
        wrong_hosts = root / "wrong_hosts"
        alien = other_host_pub.read_text().split()
        wrong_hosts.write_text(
            f"[127.0.0.1]:{port} {alien[0]} {alien[1]}\n"
        )
        os.chmod(wrong_hosts, 0o600)

        config = make_sshd_config(root, port, host_secret, authorized)
        execute("sudo", "-n", "mkdir", "-p", "/run/sshd")
        process, stream = start_sshd(config, root / "sshd.log")
        try:
            common = [
                "--host", "127.0.0.1", "--user", getpass.getuser(),
                "--port", str(port), "--known-hosts", known_hosts,
                "--identity", ssh_secret,
                "--receiver-id", "independent-ssh-loopback",
                "--source-key-id", "external-witness",
                "--source-public-key", source_pub,
                "--ack-key-id", "independent-ack",
                "--ack-public-key", ack_pub,
                "--state-dir", source,
            ]

            def seal(label):
                path = receipts / (label + ".json")
                tool(WITNESS, "seal", "--state-dir", source,
                     "--witness-key-id", "external-witness",
                     "--witness-private-key", source_secret,
                     "--output", path)
                return path

            first = seal("first")
            first_output = receipts / "first-ack.json"
            tool(CLIENT, "send", *common, "--minimum-sequence", "1",
                 "--receipt", first, "--output", first_output)
            package1 = json.loads(first_output.read_text())
            assert package1["ack"]["sequence"] == 1

            # Real host-key mismatch before any remote program runs.
            wrong_pin_output = receipts / "wrong-pin.json"
            poisoned = [wrong_hosts if x == known_hosts else x for x in common]
            tool(CLIENT, "latest", *poisoned, "--minimum-sequence", "1",
                 "--output", wrong_pin_output, success=False)
            assert not wrong_pin_output.exists()
            wrong_client = [wrong_secret if x == ssh_secret else x for x in common]
            tool(CLIENT, "latest", *wrong_client, "--minimum-sequence", "1",
                 "--output", receipts / "bad-auth.json", success=False)

            # AuthorizedKeys forced command blocks malicious user-controlled
            # remote command even though SSH authentication succeeded.
            direct = [
                "ssh", "-F", "/dev/null", "-T",
                "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=yes",
                "-o", f"UserKnownHostsFile={known_hosts}",
                "-o", "GlobalKnownHostsFile=/dev/null",
                "-o", "IdentitiesOnly=yes", "-o", "IdentityAgent=none",
                "-i", str(ssh_secret), "-p", str(port),
                "-l", getpass.getuser(), "127.0.0.1",
                "nexus-witness-v1 read-private-key",
            ]
            execute(*direct, success=False)
            assert not (root / "unexpected-execution").exists()

            # The real SSH receiver durably records a second receipt but its
            # trusted wrapper drops the reply before returning it to the client.
            tool(TRUST, "enroll", "--state-dir", source,
                 "--key-id", "data-b", "--public-key", data_pub_2)
            second = seal("second")
            marker.touch(mode=0o600)
            missing = receipts / "lost-reply.json"
            tool(CLIENT, "send", *common, "--minimum-sequence", "2",
                 "--receipt", second, "--output", missing, success=False)
            assert not missing.exists()
            assert not marker.exists(), "fault was not triggered after the durable write"
            latest_local = json.loads(
                tool(CUSTODIAN, "latest", "--store", custodian).stdout
            )
            assert latest_local["ack"]["sequence"] == 2

            # Exact retry must return the same signed acknowledgment.
            retried = receipts / "retried.json"
            tool(CLIENT, "send", *common, "--minimum-sequence", "2",
                 "--receipt", second, "--output", retried)
            assert json.loads(retried.read_text()) == latest_local
            assert json.loads(
                tool(CUSTODIAN, "latest", "--store", custodian).stdout
            ) == latest_local

            old = receipts / "old-replay.json"
            tool(CLIENT, "send", *common, "--minimum-sequence", "2",
                 "--receipt", first, "--output", old, success=False)
            assert not old.exists()
            latest_output = receipts / "latest.json"
            tool(CLIENT, "latest", *common, "--minimum-sequence", "2",
                 "--output", latest_output)
            assert json.loads(latest_output.read_text()) == latest_local

            # Actual daemon termination: no false "received" claim while
            # offline, and exact signed latest survives a fresh sshd process.
            stop_sshd(process, stream, root)
            process = None
            stream = None
            tool(CLIENT, "latest", *common, "--minimum-sequence", "2",
                 "--output", receipts / "offline-claim.json", success=False)
            process, stream = start_sshd(config, root / "sshd-restarted.log")
            resumed = receipts / "after-restart.json"
            tool(CLIENT, "latest", *common, "--minimum-sequence", "2",
                 "--output", resumed)
            assert json.loads(resumed.read_text()) == latest_local
            print(
                "REAL LOOPBACK OPENSSH NEXUS WITNESS: PASS "
                "(real sshd, pinned hostkey, forced command, reply-loss recovery, restart)"
            )
        finally:
            if process is not None and stream is not None:
                stop_sshd(process, stream, root)


if __name__ == "__main__":
    main()
